function delay(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function forceGarbageCollection(): void {
  if (global.gc) {
    global.gc();
  }
}

async function addTruckBrandsAndModels() {
  console.log(
    '🚛 Adding missing brands and models for trucks, semitrucks, special equipment, tractors and buses...\n',
  );

  if (!process.env.DB_SYNC) {
    process.env.DB_SYNC = 'false';
  }

  await AppDataSource.initialize();

  const brandRepo = AppDataSource.getRepository(Brand);
  const modelRepo = AppDataSource.getRepository(VehicleModel);

  let totalBrands = 0;
  let newBrands = 0;
  let updatedBrands = 0;
  let totalModels = 0;
  let newModels = 0;
  let updatedModels = 0;
  const missingBrands: string[] = [];

  const DELAY_BETWEEN_BRANDS = 300;
  const BATCH_SIZE = 10;
  const brandsEntries = Object.entries(TRUCK_BRANDS_AND_MODELS);

  const existingBrands = await brandRepo.find({
    select: ['id', 'name', 'vehicle_types'],
  });

  const existingBrandsMap = new Map<string, Brand>();
  for (const brand of existingBrands) {
    existingBrandsMap.set(brand.name.toLowerCase(), brand);
  }

  let order = Math.max(...existingBrands.map((b) => b.order || 0), 0) + 1;

  for (let idx = 0; idx < brandsEntries.length; idx++) {
    const [brandName, models] = brandsEntries[idx];
    const brandNameLower = brandName.toLowerCase();

    let brand = existingBrandsMap.get(brandNameLower);

    if (!brand) {
      brand = brandRepo.create({
        name: brandName,
        order,
        vehicle_types: ['truck'],
      });
      brand = await brandRepo.save(brand);
      existingBrandsMap.set(brandNameLower, brand);
      newBrands++;
      console.log(`✅ Created brand: ${brandName}`);
    } else {
      if (!brand.vehicle_types || !brand.vehicle_types.includes('truck')) {
        const vehicleTypes = brand.vehicle_types || [];
        if (!vehicleTypes.includes('truck')) {
          vehicleTypes.push('truck');
          brand.vehicle_types = vehicleTypes.sort();
          brand = await brandRepo.save(brand);
          updatedBrands++;
          console.log(`♻️  Updated brand: ${brandName} (added 'truck' type)`);
        }
      }
    }

    totalBrands++;

    const existingModels = await modelRepo.find({
      where: { brand_id: brand.id },
      select: ['id', 'name', 'order', 'vehicle_type'],
    });

    const maxOrder =
      existingModels.length > 0 ? Math.max(...existingModels.map((m) => m.order || 0)) : 0;

    const existingModelsMap = new Map<string, VehicleModel>();
    for (const model of existingModels) {
      existingModelsMap.set(model.name.toLowerCase(), model);
    }

    const modelsToCreate: VehicleModel[] = [];
    const modelsToUpdate: VehicleModel[] = [];

    for (let i = 0; i < models.length; i++) {
      const modelName = models[i];
      const modelNameLower = modelName.toLowerCase();

      const existingModel = existingModelsMap.get(modelNameLower);

      if (!existingModel) {
        let vehicleType = determineVehicleType(modelName, brandName);
        if (vehicleType !== 'truck') {
          vehicleType = 'truck';
        }
        const model = modelRepo.create({
          name: modelName,
          brand_id: brand.id,
          order: maxOrder + i + 1,
          vehicle_type: vehicleType,
        });
        modelsToCreate.push(model);
        newModels++;
      } else {
        existingModel.order = maxOrder + i + 1;
        if (!existingModel.vehicle_type || existingModel.vehicle_type !== 'truck') {
          existingModel.vehicle_type = 'truck';
        }
        modelsToUpdate.push(existingModel);
        updatedModels++;
      }
    }

    if (modelsToCreate.length > 0) {
      for (let i = 0; i < modelsToCreate.length; i += BATCH_SIZE) {
        const batch = modelsToCreate.slice(i, i + BATCH_SIZE);
        await modelRepo.save(batch);
        await delay(50);
      }
      console.log(`   ✓ Added ${modelsToCreate.length} models for ${brandName}`);
    }

    if (modelsToUpdate.length > 0) {
      for (let i = 0; i < modelsToUpdate.length; i += BATCH_SIZE) {
        const batch = modelsToUpdate.slice(i, i + BATCH_SIZE);
        await modelRepo.save(batch);
        await delay(50);
      }
      if (modelsToCreate.length === 0) {
        console.log(`   ✓ Updated ${modelsToUpdate.length} models for ${brandName}`);
      }
    }

    totalModels += models.length;

    if (idx < brandsEntries.length - 1) {
      await delay(DELAY_BETWEEN_BRANDS);
      if (idx % 20 === 0) {
        forceGarbageCollection();
      }
    }

    order++;
  }

  console.log('\n📊 SUMMARY:');
  console.log(`   Brands: processed ${totalBrands}, new ${newBrands}, updated ${updatedBrands}`);
  console.log(`   Models: processed ${totalModels}, new ${newModels}, updated ${updatedModels}`);

  if (missingBrands.length > 0) {
    console.warn(`\n⚠️  Skipped brands (${missingBrands.length}): ${missingBrands.join(', ')}`);
  }

  const summary = {
    brandsProcessed: totalBrands,
    brandsCreated: newBrands,
    brandsUpdated: updatedBrands,
    modelsProcessed: totalModels,
    modelsInserted: newModels,
    modelsUpdated: updatedModels,
  };

  console.log('\n' + JSON.stringify(summary, null, 2));

  await AppDataSource.destroy();
}

if (require.main === module) {
  addTruckBrandsAndModels()
    .then(() => {
      console.log('\n✅ Done!');
      process.exit(0);
    })
    .catch((error) => {
      console.error('❌ Error:', error);
      process.exit(1);
    });
}

export { addTruckBrandsAndModels };
