export function getBrandCategory(
  brandName: string,
): 'truck_only' | 'moto_only' | 'mixed' | 'car_default' {
  const brandLower = brandName.toLowerCase();

  if (TRUCK_ONLY_BRANDS.some((b) => b.toLowerCase() === brandLower)) {
    return 'truck_only';
  }

  if (MOTO_ONLY_BRANDS.some((b) => b.toLowerCase() === brandLower)) {
    return 'moto_only';
  }

  if (Object.keys(MIXED_BRANDS).some((b) => b.toLowerCase() === brandLower)) {
    return 'mixed';
  }

  return 'car_default';
}

export function determineVehicleType(
  modelName: string,
  brandName: string,
): 'car' | 'truck' | 'moto' {
  const brandLower = brandName.toLowerCase();
  const modelLower = modelName.toLowerCase();

  if (TRUCK_ONLY_BRANDS.some((b) => b.toLowerCase() === brandLower)) {
    return 'truck';
  }

  if (MOTO_ONLY_BRANDS.some((b) => b.toLowerCase() === brandLower)) {
    return 'moto';
  }

  const mixedBrandKey = Object.keys(MIXED_BRANDS).find((b) => b.toLowerCase() === brandLower);
  if (mixedBrandKey) {
    const mixedBrand = MIXED_BRANDS[mixedBrandKey];

    for (const carModel of mixedBrand.car) {
      if (modelLower.includes(carModel.toLowerCase())) {
        return 'car';
      }
    }

    for (const truckModel of mixedBrand.truck) {
      if (modelLower.includes(truckModel.toLowerCase())) {
        return 'truck';
      }
    }

    for (const motoModel of mixedBrand.moto) {
      if (modelLower.includes(motoModel.toLowerCase())) {
        return 'moto';
      }
    }

    return 'car';
  }

  return 'car';
}
