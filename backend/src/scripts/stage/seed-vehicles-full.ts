async function seedFullVehiclesDatabase() {
  console.log('🌱 Starting full vehicle database seeding...');

  await AppDataSource.initialize();

  const brandRepo = AppDataSource.getRepository(Brand);
  const modelRepo = AppDataSource.getRepository(VehicleModel);

  let order = 1;
  let totalModels = 0;

  for (const [brandName, models] of Object.entries(BRANDS_AND_MODELS)) {
    let brand = await brandRepo.findOne({ where: { name: brandName } });

    if (!brand) {
      const initialVehicleType =
        models.length > 0 ? determineVehicleType(models[0], brandName) : 'car';
      brand = brandRepo.create({
        name: brandName,
        order,
        vehicle_types: [initialVehicleType],
      });
      brand = await brandRepo.save(brand);
      console.log(`✅ Created brand: ${brandName}`);
    } else {
      brand.order = order;
      brand = await brandRepo.save(brand);
      console.log(`♻️  Updated brand: ${brandName}`);
    }

    for (let i = 0; i < models.length; i++) {
      const modelName = models[i];
      let model = await modelRepo.findOne({
        where: { name: modelName, brand_id: brand.id },
      });

      if (!model) {
        const vehicleType = determineVehicleType(modelName, brandName);
        model = modelRepo.create({
          name: modelName,
          brand_id: brand.id,
          order: i + 1,
          vehicle_type: vehicleType,
        });
        await modelRepo.save(model);
        totalModels++;
      } else {
        model.order = i + 1;
        await modelRepo.save(model);
      }
    }

    const allModelsForBrand = await modelRepo.find({
      where: { brand_id: brand.id },
      select: ['vehicle_type'],
    });
    const vehicleTypes = new Set<'car' | 'truck' | 'moto'>();
    for (const model of allModelsForBrand) {
      if (model.vehicle_type) {
        vehicleTypes.add(model.vehicle_type);
      }
    }
    if (vehicleTypes.size > 0) {
      brand.vehicle_types = Array.from(vehicleTypes).sort();
      await brandRepo.save(brand);
    } else if (!brand.vehicle_types || brand.vehicle_types.length === 0) {
      const initialVehicleType =
        models.length > 0 ? determineVehicleType(models[0], brandName) : 'car';
      brand.vehicle_types = [initialVehicleType];
      await brandRepo.save(brand);
    }

    console.log(`  ✓ ${models.length} models for ${brandName}`);
    order++;
  }

  console.log(`\n✅ Complete!`);
  console.log(`   - Brands: ${Object.keys(BRANDS_AND_MODELS).length}`);
  console.log(`   - Total models: ${Object.values(BRANDS_AND_MODELS).flat().length}`);
  console.log(`   - New models: ${totalModels}`);
  console.log(`\n🎨 Standard colors (${COLORS.length}):`);
  COLORS.forEach((color, index) => {
    if (index < COLORS.length - 1) {
      process.stdout.write(`${color}, `);
    } else {
      console.log(color);
    }
  });

  await AppDataSource.destroy();
}

seedFullVehiclesDatabase()
  .then(() => {
    console.log('\n✨ Script completed successfully!');
    process.exit(0);
  })
  .catch((error) => {
    console.error('❌ Error:', error);
    process.exit(1);
  });
